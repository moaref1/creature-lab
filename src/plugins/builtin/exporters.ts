const ident = (s: string) => s.replace(/[^A-Za-z0-9]/g, ' ').replace(/(?:^|\s+)(\w)/g, (_m, c) => c.toUpperCase()).replace(/\s/g, '') || 'Agent';
const snake = (s: string) => s.replace(/[^A-Za-z0-9]+/g, '_').replace(/^_|_$/g, '').toLowerCase() || 'agent';

function brainName(p: ProjectDoc, c: CheckpointDoc) {
  return p.brains.find((b) => b.id === c.brainId)?.name ?? 'Agent';
}

function commonChecks(p: ProjectDoc, c: CheckpointDoc): CheckResult[] {
  const out: CheckResult[] = [];
  const spec = c.spec;
  out.push({ ok: true, level: 'info', message: `${spec.obsLabels.length} inputs → ${spec.actions.length} actions, network ${[spec.obsLabels.length, ...spec.hidden].join('×')}.` });
  const run = p.runs.find((r) => r.id === c.runId);
  for (const [k, h] of Object.entries(c.hashes ?? {})) {
    if (!k.startsWith('prefab:')) continue;
    const pf = p.prefabs.find((x) => `prefab:${x.id}` === k);
    if (pf && !h.startsWith(`v${pf.version}:`))
      out.push({ ok: false, level: 'warn', message: `"${pf.name}" changed since this brain was trained (trained on ${h.split(':')[0]}, now v${pf.version}). Sensors or actions may no longer match the game.` });
  }
  if (spec.obsLabels.some((l) => l.includes('msg') || l.startsWith('bb.') || l.startsWith('goal='))) out.push({ ok: true, level: 'warn', message: 'Inputs include blackboard/messages: the game must supply them (an upper brain layer or team channel).' });
  if (!run) out.push({ ok: true, level: 'info', message: 'Checkpoint is not linked to a run in this project (imported).' });
  if (c.score === 0 && c.step === 0) out.push({ ok: false, level: 'warn', message: 'This checkpoint has not been trained yet.' });
  return out;
}

function ioTable(c: CheckpointDoc) {
  const rows = c.spec.obsLabels.map((l, i) => `| ${i} | \`${l}\` |`).join('\n');
  let k = 0;
  const acts = c.spec.actions
    .map((a) => (a.kind === 'cont' ? `| continuous_actions[${k++}] | \`${a.name}\` | -1 … 1 |` : `| discrete_logits (argmax) | \`${a.name}\` | ${a.options?.join(', ')} |`))
    .join('\n');
  return `## Inputs (observation vector, in order)\n\n| # | Input |\n|---|---|\n${rows}\n\n## Outputs\n\n| Tensor | Action | Range / options |\n|---|---|---|\n${acts}\n`;
}

function readme(target: string, p: ProjectDoc, c: CheckpointDoc, body: string) {
  return `# ${brainName(p, c)} — ${target} package\n\nExported from Creature Lab project **${p.name}** on ${new Date().toISOString().slice(0, 10)}.\nCheckpoint: \`${c.id}\` · ${c.step.toLocaleString()} training steps · score ${c.score.toFixed(3)}.\n\n${body}\n\n${ioTable(c)}\nThe observation vector must be produced in exactly this order, with the same units the studio sensors use (see the sensor docs in the studio). The model normalises inputs itself.\n`;
}

function base(p: ProjectDoc, c: CheckpointDoc) {
  const pol = Policy.fromCheckpoint(c, false);
  const meta = { brain: brainName(p, c), checkpoint: c.id, spec: JSON.stringify(c.spec) };
  return { pol, onnx: policyToOnnx(pol, meta), json: JSON.stringify(policyToJson(pol)), meta };
}

