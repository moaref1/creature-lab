const PY_POLICY = `"""Generated by Creature Lab: numpy inference for the trained policy."""
import json
import numpy as np


class Policy:
    def __init__(self, path):
        with open(path) as f:
            s = json.load(f)
        self.spec = s
        self.mean = np.array(s["norm"]["mean"], dtype=np.float32)
        self.std = np.array(s["norm"]["std"], dtype=np.float32)
        self.clip = s["norm"]["clip"]
        self.layers = [(np.array(L["W"], dtype=np.float32).reshape(L["out"], L["in"]), np.array(L["b"], dtype=np.float32)) for L in s["layers"]]
        self.act_fn = np.tanh if s["activation"] == "tanh" else (lambda v: np.maximum(v, 0))
        self.n_cont = s["continuous"]
        self.disc = s["discreteSizes"]
        self.obs_labels = s["obsLabels"]
        self.actions = s["actions"]

    def __call__(self, obs):
        x = np.clip((np.asarray(obs, dtype=np.float32) - self.mean) / self.std, -self.clip, self.clip)
        for i, (W, b) in enumerate(self.layers):
            x = W @ x + b
            if i < len(self.layers) - 1:
                x = self.act_fn(x)
        cont = np.clip(x[: self.n_cont], -1, 1)
        disc, off = [], self.n_cont
        for k in self.disc:
            disc.append(int(np.argmax(x[off : off + k])))
            off += k
        return cont, disc
`;

